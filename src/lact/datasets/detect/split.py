"""2DeteCT split: LION's sample-level split, the random draw of slices and the generated split files."""
from __future__ import annotations

import csv
import datetime as _dt
import logging
import os
from pathlib import Path

import numpy as np

log = logging.getLogger("lact")

SLICES_CSV = "detect_slices.csv"


def lion_split(records_csv: str | os.PathLike) -> dict[str, list[int]]:
    """Slices (1..5000) of each split in LION's split: 109 samples in order of appearance, the first 80 % train, the
    next 10 % validation, the last int(10 %) samples test (the exact expressions of ``LION/data_loaders/deteCT.py``)."""
    with open(records_csv, newline="") as f:
        rows = [(int(r["slice_identifier"][5:]), int(r["sample_index"])) for r in csv.DictReader(f)]
    samples = list(dict.fromkeys(s for _, s in rows))
    n, tr, va = len(samples), 0.8, 0.1
    parts = {"train": samples[:int(n * tr)], "val": samples[int(n * tr):int(n * (tr + va))],
             "test": samples[-int(n * (1 - tr - va)):]}
    return {k: sorted(i for i, s in rows if s in set(v)) for k, v in parts.items()}


def select_slices(records_csv: str | os.PathLike, n_train: int = 2000, n_val: int = 200, n_test: int | None = None,
                  seed: int = 0) -> list[dict]:
    """Draw without replacement from each LION split (None or more than available = take all). "Patient" = sample."""
    with open(records_csv, newline="") as f:
        sample = {int(r["slice_identifier"][5:]): int(r["sample_index"]) for r in csv.DictReader(f)}
    rng = np.random.default_rng(seed)
    rows = []
    for split, want in (("train", n_train), ("val", n_val), ("test", n_test)):
        pool = lion_split(records_csv)[split]
        pick = pool if want is None or want >= len(pool) else sorted(rng.choice(pool, want, replace=False).tolist())
        rows += [{"slice": i, "split": split, "patient": f"DT{sample[i]:03d}"} for i in pick]
    return rows


def read_slices(path: str | os.PathLike) -> list[dict]:
    with open(path, newline="", encoding="utf-8") as f:
        return [{"slice": int(r["slice"]), "split": r["split"], "patient": r["patient"]}
                for r in csv.DictReader(line for line in f if not line.startswith("#"))]


def _flow(key: str, items: list[str], indent: str = "  ", width: int = 110) -> str:
    out, line = [], f"{indent}{key}: ["
    for i, it in enumerate(items):
        piece = it + (", " if i < len(items) - 1 else "")
        if len(line) + len(piece) > width:
            out.append(line.rstrip())
            line = indent + " " * (len(key) + 3)
        line += piece
    out.append(line + "]")
    return "\n".join(out) + "\n"


def write_split_configs(rows: list[dict], cfg_dir: str | os.PathLike = "configs/data", seed: int = 0) -> dict:
    """Write ``detect_slices.csv`` (the single source of the draw), ``detect_patients.yaml`` (data.patients) and
    ``split_detect.yaml``. Never edit these files by hand."""
    cfg_dir = Path(cfg_dir)
    n = {k: sum(r["split"] == k for r in rows) for k in ("train", "val", "test")}
    pat = {k: sorted({r["patient"] for r in rows if r["split"] == k}) for k in n}
    today = _dt.date.today().isoformat()
    rule = (f"{n['train']} / {n['val']} / {n['test']} slices drawn at random (seed {seed}) from the three splits of "
            "LION's sample-level split (3930 / 550 / 470 slices)")
    with open(cfg_dir / SLICES_CSV, "w", encoding="utf-8", newline="") as f:
        f.write(f"# 2DeteCT: {rule}; generated by `lact data split-2detect` ({today}). Do not edit by hand.\n")
        w = csv.DictWriter(f, fieldnames=["slice", "split", "patient"])
        w.writeheader()
        w.writerows(rows)
    head = f"# Generated by `lact data split-2detect` from configs/data/{SLICES_CSV}; do not edit by hand.\n"
    every = pat["train"] + pat["val"] + pat["test"]
    (cfg_dir / "detect_patients.yaml").write_text(
        head + f"# 2DeteCT samples ({len(every)}; each sample holds only its drawn slices).\ndata:\n"
        + _flow("patients", every),
        encoding="utf-8")
    (cfg_dir / "split_detect.yaml").write_text(
        head + f"# 2DeteCT: {rule}.\n#   train {n['train']} slices / {len(pat['train'])} samples, validation "
        f"{n['val']} slices / {len(pat['val'])} samples, test {n['test']} slices / {len(pat['test'])} samples. Each "
        "sample is in one split only.\nsplit:\n  name: split_detect\n"
        + _flow("train", pat["train"]) + _flow("val", pat["val"]) + _flow("test", pat["test"]), encoding="utf-8")
    log.info("Wrote %s, detect_patients.yaml, split_detect.yaml: %s slices, %s samples", cfg_dir / SLICES_CSV, n,
             {k: len(v) for k, v in pat.items()})
    return {"n_slices": n, "patients": pat}
