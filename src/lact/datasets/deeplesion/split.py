"""DeepLesion splits: the patient-level split of the deeplesion variant and the phase-2 key-slice draw with the
joint-store configuration files generated from it."""
from __future__ import annotations

import csv
import datetime as _dt
import logging
import os
from pathlib import Path

import numpy as np

from ...config.loader import load_yaml, save_yaml
from . import reader as dl
from .reader import INFO_CSV

log = logging.getLogger("lact")

KEY_MANIFEST = "deeplesion_keyslices.csv"      # in configs/data: list of drawn slices (the single source of the draw)


def make_split(root: str | os.PathLike, out_yaml: str | os.PathLike, n_train: int = 45, n_val: int = 6,
               n_test: int = 15, min_slices: int = 20, info_csv: str | os.PathLike | None = None,
               size: int = 512) -> dict:
    """Pick the patients of the three splits and write ``out_yaml`` (``split`` and ``data.patients`` sections).

    Rule (blind to model results): walk the patients by increasing id, accept only patients with at least
    ``min_slices`` usable ``size`` x ``size`` slices; each patient goes to the split given by the OFFICIAL
    Train_Val_Test
    column of DL_info.csv, stopping once each split is full. Without DL_info.csv patients are assigned in id order
    (with a warning).
    """
    root = Path(root)
    info_path = Path(info_csv) if info_csv else root / INFO_CSV
    info = dl.load_info(info_path)
    official = dl.official_split(info)
    if not official:
        log.warning("No official split (%s); assigning patients in id order", info_path)
    want = {"train": int(n_train), "val": int(n_val), "test": int(n_test)}
    picked: dict[str, list[str]] = {k: [] for k in want}
    counts: dict[str, int] = {}
    for pid, dirs in sorted(dl.find_series(root).items()):
        if all(len(picked[k]) >= want[k] for k in want):
            break
        target = official.get(pid) if official else next((k for k in want if len(picked[k]) < want[k]), None)
        if target is None or len(picked[target]) >= want[target]:
            continue
        n = len(dl.patient_slices(dirs, info, size))
        if n < min_slices:
            continue
        picked[target].append(pid)
        counts[pid] = n
    short = {k: (len(picked[k]), want[k]) for k in want if len(picked[k]) < want[k]}
    if short:
        raise RuntimeError(f"Not enough patients (have, need): {short}. Download more zip files: lact data "
                           "download-deeplesion --zips ...")
    name = f"deeplesion_{n_train}_{n_val}_{n_test}"
    doc = {"data": {"patients": picked["train"] + picked["val"] + picked["test"]},
           "split": {"name": name, **picked}}
    save_yaml(doc, out_yaml)
    out = Path(out_yaml)
    header = (f"# Patient-level DeepLesion split, generated by `lact data split-deeplesion` "
              f"({_dt.date.today().isoformat()}).\n"
              f"# Rule: increasing patient id, >= {min_slices} slices of {size}x{size}, split from the official "
              f"Train_Val_Test column.\n# Do not edit by hand: every run of the deeplesion variant shares this file.\n")
    out.write_text(header + out.read_text(encoding="utf-8"), encoding="utf-8")
    log.info("Wrote %s: train %d, val %d, test %d patients", out, n_train, n_val, n_test)
    return {"split": picked, "usable_slices": counts, "file": str(out)}


def select_key_slices(info_csv: str | os.PathLike, n_train: int = 2000, n_val: int = 200, n_test: int = 300,
                      seed: int = 0, size: int = 512) -> list[dict]:
    """Draw key slices at random from each OFFICIAL split (Train_Val_Test column of DL_info.csv, patient-level):
    ``n_train`` / ``n_val`` / ``n_test`` slices without repetition. This is how QN-Mixer ("a subset of 2000 training
    images and 300 testing images randomly from the official splits") and CG-GLORE (2,000 / 200 / 300) use the dataset.

    Only ``size`` x ``size`` slices of series not flagged as noisy are eligible. Blind to model results. Returns
    [{file_name, split, patient}] ordered by (split, file name)."""
    import pandas as pd

    df = pd.read_csv(info_csv)
    df.columns = [c.strip() for c in df.columns]
    df["series"] = df.File_name.astype(str).str.rsplit("_", n=1).str[0]
    noisy = set(df[df.Possibly_noisy.astype(str).str.strip() == "1"].series)
    keys = df.drop_duplicates("File_name")
    ok = ((keys.Image_size.astype(str).str.replace(" ", "") == f"{size},{size}") & ~keys.series.isin(noisy)
          & keys.series.map(lambda v: bool(dl.SERIES_RE.match(v))))
    keys = keys[ok]
    want = {"train": int(n_train), "val": int(n_val), "test": int(n_test)}
    rng = np.random.default_rng(seed)
    rows: list[dict] = []
    for code, name in dl.OFFICIAL_SPLIT.items():
        pool = sorted(keys[keys.Train_Val_Test == code].File_name.astype(str))
        if len(pool) < want[name]:
            raise RuntimeError(f"The official {name} split has only {len(pool)} usable slices, {want[name]} needed")
        for i in sorted(rng.choice(len(pool), size=want[name], replace=False).tolist()):
            rows.append({"file_name": pool[i], "split": name, "patient": dl.patient_id(pool[i])})
    owner: dict[str, str] = {}
    for r in rows:
        if owner.setdefault(r["patient"], r["split"]) != r["split"]:
            raise ValueError(f"Patient {r['patient']} belongs to two different official splits")
    return rows


def read_key_manifest(path: str | os.PathLike) -> list[dict]:
    with open(path, encoding="utf-8", newline="") as f:
        return [r for r in csv.DictReader(line for line in f if not line.startswith("#"))]


def _flow(key: str, items: list[str], width: int = 118) -> str:
    """One YAML key with an inline list ([a, b, ...]) that wraps lines."""
    lines, cur = [], f"  {key}: ["
    pad = " " * (len(key) + 5)
    for i, it in enumerate(items):
        tok = it + ("," if i < len(items) - 1 else "]")
        if len(cur) + len(tok) + 1 > width and cur.strip():
            lines.append(cur.rstrip())
            cur = pad
        cur += tok + " "
    if not items:
        cur += "]"
    lines.append(cur.rstrip())
    return "\n".join(lines) + "\n"


def write_key_slice_configs(rows: list[dict], cfg_dir: str | os.PathLike = "configs/data",
                            mayo_split: str | os.PathLike = "configs/data/split_7_1_2.yaml", seed: int = 0) -> dict:
    """Write the list of drawn slices and the joint-store configuration files derived from it (never edit them by
    hand): ``deeplesion_keyslices.csv``, ``joint_patients.yaml`` (data.patients), ``split_joint.yaml``,
    ``split_joint_dl.yaml``, ``split_joint_mayo.yaml``."""
    cfg_dir = Path(cfg_dir)
    mayo = load_yaml(mayo_split)["split"]
    n = {k: sum(r["split"] == k for r in rows) for k in ("train", "val", "test")}
    pat = {k: sorted({r["patient"] for r in rows if r["split"] == k}) for k in n}
    today = _dt.date.today().isoformat()
    rule = (f"{n['train']} / {n['val']} / {n['test']} key slices drawn at random (seed {seed}) from the three "
            "official splits")
    with open(cfg_dir / KEY_MANIFEST, "w", encoding="utf-8", newline="") as f:
        f.write(f"# DeepLesion for phase 2: {rule}; generated by `lact data split-deeplesion --key-slices` ({today}).\n"
                "# As in QN-Mixer and CG-GLORE. Do not edit by hand: this is the single source of the draw.\n")
        w = csv.DictWriter(f, fieldnames=["file_name", "split", "patient"])
        w.writeheader()
        w.writerows(rows)
    head = ("# Generated by `lact data split-deeplesion --key-slices` from configs/data/deeplesion_keyslices.csv; "
            "do not edit by hand.\n")
    mayo_all = sorted(list(mayo["train"]) + list(mayo["val"]) + list(mayo["test"]))     # order of mayo_3mm.yaml
    dl_all = pat["train"] + pat["val"] + pat["test"]
    (cfg_dir / "joint_patients.yaml").write_text(
        head + f"# Patients of the joint store: Mayo {len(mayo_all)} + DeepLesion {len(dl_all)} (each DeepLesion "
               "patient holds only its drawn key slices).\ndata:\n" + _flow("patients",
                                                                            mayo_all + dl_all), encoding="utf-8")
    test = list(mayo["test"]) + pat["test"]
    info = (f"DeepLesion: {rule}\n#   train {n['train']} slices / {len(pat['train'])} patients, validation "
            f"{n['val']} slices / {len(pat['val'])} patients, test {n['test']} slices / {len(pat['test'])} patients.\n")
    docs = {
        "split_joint": ("# Train on BOTH datasets; test on both (reported per dataset). Used for data-level "
                        "commands\n# (building the store, TV tuning, baselines).\n",
                        list(mayo["train"]) + pat["train"], list(mayo["val"]) + pat["val"]),
        "split_joint_dl": ("# Train ONLY on DeepLesion, select models on the DeepLesion validation split; test on "
                           "DeepLesion (in-domain)\n# and Mayo L310, L506 (cross-domain: DeepLesion -> Mayo).\n",
                           pat["train"], pat["val"]),
        "split_joint_mayo": ("# The Mayo 7/1/2 split (configs/data/split_7_1_2.yaml) on the joint store: validation "
                             "is still L333, so E3 runs\n# reproduce their validation PSNR; test on Mayo (in-domain) "
                             "and DeepLesion (cross-domain: Mayo -> DeepLesion).\n",
                             list(mayo["train"]), list(mayo["val"])),
    }
    for name, (why, train, val) in docs.items():
        (cfg_dir / f"{name}.yaml").write_text(
            head + "# Split on the joint store (configs/data/joint.yaml). Each patient is in one split only.\n" + why
            + "# " + info + f"split:\n  name: {name}\n" + _flow("train", train) + _flow("val", val)
            + _flow("test", test), encoding="utf-8")
    log.info("Wrote %s and the joint-store files: DeepLesion %s slices, %s patients", cfg_dir / KEY_MANIFEST, n,
             {k: len(v) for k, v in pat.items()})
    return {"n_slices": n, "patients": pat}
